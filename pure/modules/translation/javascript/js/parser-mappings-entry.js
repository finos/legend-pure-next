// esbuild --bundle entry: the MAPPINGS HALF of what used to be a single
// antlr-bundle.js — the translated parser-mappings interpreter plus the
// `__pureParseTop` entry point the translator emits for Pure's `parse`.
//
// Split out from antlr-entry.js because this half needs pure-truffle and the
// javascript/translation PDBs to exist (antlr-generate-ts-parserMapping
// translates meta::pure::parser::mappings), while the parser half needs none
// of that. Keeping them apart lets the extension jar be packaged from the
// parser half alone, upstream of any PDB — see antlr-entry.js.
//
// LOAD ORDER: antlr-bundle.js MUST be eval'd first. This bundle reads
// `globalThis.__parseAntlr` (published there) at call time, not load time,
// so the two are order-tolerant at definition but not at first parse.

// The translated parser-mappings interpreter (parseDocument + 118 helpers).
// Generated by the `antlr-generate-ts-parserMapping` recipe via the existing
// pdb-to-js pipeline. Importing it in this bundle means every helper stays in
// its sibling functions' lexical closures — `parseDocument` finds
// `buildSection`, etc. without needing globalThis lookups internally; we only
// publish the top-level entry points.
import * as pm from "./build/parser-mappings.js";

const g = globalThis;

// Expose every translated parser-mappings function on globalThis. The
// recursive descent inside parseDocument's body reaches its siblings via
// the IIFE's closure — exposing them globally is mostly so debug/REPL
// access works (e.g. calling `globalThis.buildClass(ctx, 0)` from a JS
// inspector). Object.assign over the namespace import re-publishes every
// `export function` without enumerating them by name.
Object.assign(g, pm);

// `parse(sourceId, content)` from Pure resolves to this helper via
// `parseCoder` in translation.pure. Mirrors `TrufflePureParser.parse`:
// prepend a synthetic ###Pure header when none is present so the
// island grammar recognises the body as a Pure section, drive the Top
// parser, then hand the resulting AntlrContext to the translated
// parser-mappings `parseDocument` along with the section-parser registry.
g.__pureParseTop = (sourceId, content) => {
    if (typeof g.__parseAntlr !== "function") {
        throw new Error(
            "__parseAntlr is not defined — antlr-bundle.js must be evaluated " +
            "before parser-mappings-bundle.js");
    }
    const syntheticHeader = !content.startsWith("###");
    const effective = syntheticHeader ? "###Pure\n" + content : content;
    const ctx = g.__parseAntlr(effective, "TopParser", sourceId, 0n);
    // Functions are emitted under their full-path, signature-mangled names
    // (Pure overloads / cross-package name reuse can't share a JS identifier).
    return pm.meta$pure$parser$mappings$interpreter$parseDocument_AntlrContext_1__String_1__Boolean_1__Pair_MANY__PureFile_1_(
        ctx, sourceId, syntheticHeader, [pm.meta$pure$parser$mappings$interpreter$pureSectionParser__Pair_1_()]);
};
